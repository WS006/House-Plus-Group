/**
 * Generates client/src/lib/imageManifest.ts from the real files on disk.
 *
 * Why: <img> needs intrinsic width/height to reserve layout space, but product
 * photos come in mixed aspect ratios (1200x800, 1200x1800, 1200x1500...). Rather
 * than hand-maintaining a table that silently rots, derive it from the source.
 *
 * Run: node tools/generate-image-manifest.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = path.join(root, 'client', 'public', 'images');
const outFile = path.join(root, 'client', 'src', 'lib', 'imageManifest.ts');

const entries = [];
const walk = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    // images/og are fixed-size share cards referenced only by meta tags, never
    // rendered as <img>, so they don't need intrinsic sizes in the manifest.
    if (e.isDirectory()) { if (e.name !== 'og') walk(p); continue; }
    if (!/\.(jpe?g|png)$/i.test(e.name)) continue;
    const rel = '/' + path.relative(path.join(root, 'client', 'public'), p).replace(/\\/g, '/');
    entries.push({ rel, abs: p });
  }
};

walk(imagesDir);

const rows = [];
for (const { rel, abs } of entries.sort((a, b) => a.rel.localeCompare(b.rel))) {
  const { width, height } = await sharp(abs).metadata();
  rows.push(`  '${rel}': { width: ${width}, height: ${height} },`);
}

const content = `// AUTO-GENERATED by tools/generate-image-manifest.mjs — do not edit by hand.
// Intrinsic dimensions of every raster image in client/public/images, used to
// emit width/height on <img> so the browser reserves layout space (avoids CLS).

export interface ImageSize {
  width: number;
  height: number;
}

export const IMAGE_SIZES: Record<string, ImageSize> = {
${rows.join('\n')}
};

/** Fallback used for unknown images: a neutral 4:3 box. */
const FALLBACK: ImageSize = { width: 1200, height: 900 };

export function getImageSize(src: string | undefined): ImageSize {
  if (!src) return FALLBACK;
  const key = src.replace(/\\.(jpe?g|png|webp)$/i, (m) => (m === '.png' ? '.png' : '.jpg'));
  return IMAGE_SIZES[key] ?? IMAGE_SIZES[src] ?? FALLBACK;
}
`;

fs.writeFileSync(outFile, content, 'utf8');
console.log(`✓ wrote ${rows.length} image dimensions to client/src/lib/imageManifest.ts`);
